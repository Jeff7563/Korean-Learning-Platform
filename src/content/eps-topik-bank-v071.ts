const answerSlots = [
  [2, 0, 3, 1, 1, 3, 0, 2, 3, 1, 2, 0, 0, 2, 1, 3, 2, 3, 1, 0],
  [1, 2, 0, 3, 3, 0, 2, 1, 0, 3, 1, 2, 2, 1, 3, 0, 1, 0, 3, 2],
  [3, 1, 0, 2, 0, 2, 1, 3, 2, 0, 3, 1, 1, 3, 2, 0, 3, 2, 0, 1],
  [0, 3, 2, 1, 2, 1, 3, 0, 1, 2, 0, 3, 3, 0, 1, 2, 0, 1, 2, 3],
];
function makeSection(section: EpsQuestionDraft["section"], items: Item[], slots: number[]): EpsQuestionDraft[] {
  return items.map(([skill, prompt, correct, wrong1, wrong2, wrong3, explanation, script], index) => {
    const options = [wrong1, wrong2, wrong3];
    const answer = slots[index];
    options.splice(answer, 0, correct);
    return { section, skill, prompt, options: options as [string, string, string, string], answer, explanation, ...(script ? { script } : {}) };
  });
}

