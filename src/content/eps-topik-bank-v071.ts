export function validateEpsExamDrafts(drafts = epsExamDraftsV071) {
  const positionSequences: string[] = [];
  for (const exam of drafts) {
    if (exam.questions.length !== 40) throw new Error(`${exam.id} must contain 40 questions`);
    for (const section of ["reading", "listening"] as const) {
      const questions = exam.questions.filter((question) => question.section === section);
      positionSequences.push(questions.map((question) => question.answer).join(""));
      if (questions.length !== 20) throw new Error(`${exam.id} must contain 20 ${section} questions`);
      const counts = [0, 0, 0, 0];
      for (const question of questions) {
        if (question.options.length !== 4 || new Set(question.options).size !== 4 || question.answer < 0 || question.answer > 3) throw new Error(`${exam.id} has an invalid question`);
        counts[question.answer]++;
        if (!question.explanation.trim() || (section === "listening" && !question.script?.trim())) throw new Error(`${exam.id} has missing review content`);
        if (section === "reading" && !/[가-힣]/u.test(question.prompt)) throw new Error(`${exam.id} has a non-Korean reading prompt`);
        if (section === "reading" && question.options.some((option) => !/[가-힣]/u.test(option))) throw new Error(`${exam.id} has a non-Korean reading choice at item ${questions.indexOf(question) + 1}: ${question.options.join(" | ")}`);
      }
      if (counts.some((count) => count !== 5)) throw new Error(`${exam.id} ${section} answer positions are not balanced: ${counts.join(",")}`);
    }
  }
  if (new Set(positionSequences).size !== positionSequences.length) throw new Error("Each exam section must use a distinct answer-position sequence");
}

